/**
 * Promise timeout wrapper
 */
export function withTimeout<T>(promise: Promise<T>, timeoutMs: number, errorMessage: string): Promise<T> {
  let timer: any;
  const timeoutPromise = new Promise<never>((_, reject) => {
    timer = setTimeout(() => {
      const err: any = new Error(errorMessage);
      err.code = 'timeout';
      reject(err);
    }, timeoutMs);
  });
  return Promise.race([promise, timeoutPromise]).finally(() => {
    clearTimeout(timer);
  });
}

/**
 * Format Firebase errors with user-friendly French and Arabic messages
 */
export function formatFirebaseErrorMessage(
  error: any,
  lang: 'fr' | 'ar' = 'fr'
): { code: string; message: string; friendly: string } {
  const code = error?.code || (error?.message?.includes('timed out') || error?.message?.includes('Délai') ? 'timeout' : 'unknown');
  const rawMessage = error?.message || String(error);

  let friendly = '';
  switch (code) {
    case 'permission-denied':
      friendly = lang === 'ar'
        ? 'تم رفض الإذن من الخادم (راجع قواعد الأمان Firestore Rules).'
        : 'Permission refusée par le serveur (vérifiez les règles Firestore).';
      break;
    case 'unavailable':
      friendly = lang === 'ar'
        ? 'الخدمة غير متوفرة حالياً، يرجى التحقق من اتصال الإنترنت أو خادم Firebase.'
        : 'Service temporairement indisponible. Vérifiez votre connexion Internet.';
      break;
    case 'failed-precondition':
      friendly = lang === 'ar'
        ? 'فشل شرط مسبق في قاعدة البيانات (تأكد من إنشاء قاعدة البيانات Firestore).'
        : 'Condition préalable échouée (vérifiez que la base Firestore est bien créée et active).';
      break;
    case 'timeout':
      friendly = lang === 'ar'
        ? 'انتهت مهلة الاتصال بالخادم دون استجابة (Timeout).'
        : 'Délai d’attente dépassé sans réponse du serveur (Timeout).';
      break;
    case 'invalid-argument':
      friendly = lang === 'ar'
        ? 'بيانات غير صالحة تم إرسالها إلى قاعدة البيانات.'
        : 'Données invalides transmises à la base de données.';
      break;
    default:
      friendly = lang === 'ar'
        ? `خطأ أثناء الاتصال بالخادم: ${rawMessage}`
        : `Erreur serveur : ${rawMessage}`;
  }

  return { code, message: rawMessage, friendly };
}

/**
 * Always resize and compress in the browser BEFORE any upload:
 * max 800px longest side, JPEG quality 0.6, reduce quality step by step until under 300 KB.
 */
export async function compressImageFile(file: File): Promise<{ dataUrl: string; blob: Blob }> {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onerror = () => reject(new Error('Erreur de lecture du fichier image'));
    reader.onload = () => {
      const img = new Image();
      img.onerror = () => reject(new Error('Erreur de chargement de l’image dans le navigateur'));
      img.onload = () => {
        let width = img.width;
        let height = img.height;
        const maxDimension = 800;

        if (width > maxDimension || height > maxDimension) {
          if (width > height) {
            height = Math.round((height * maxDimension) / width);
            width = maxDimension;
          } else {
            width = Math.round((width * maxDimension) / height);
            height = maxDimension;
          }
        }

        const canvas = document.createElement('canvas');
        canvas.width = Math.max(1, width);
        canvas.height = Math.max(1, height);
        const ctx = canvas.getContext('2d');
        if (!ctx) {
          return reject(new Error('Impossible de créer le contexte canvas 2D'));
        }

        ctx.drawImage(img, 0, 0, width, height);

        // Target under 300 KB (300 * 1024 * (4/3) ~= 409,600 base64 chars)
        const targetMaxChars = 380000;
        let quality = 0.6;
        let dataUrl = canvas.toDataURL('image/jpeg', quality);

        // Reduce quality step by step until under 300 KB
        while (dataUrl.length > targetMaxChars && quality > 0.15) {
          quality -= 0.1;
          dataUrl = canvas.toDataURL('image/jpeg', quality);
        }

        // Convert to Blob for Firebase Storage
        canvas.toBlob(
          (blob) => {
            if (blob) {
              resolve({ dataUrl, blob });
            } else {
              const byteString = atob(dataUrl.split(',')[1]);
              const ab = new ArrayBuffer(byteString.length);
              const ia = new Uint8Array(ab);
              for (let i = 0; i < byteString.length; i++) {
                ia[i] = byteString.charCodeAt(i);
              }
              const fallbackBlob = new Blob([ab], { type: 'image/jpeg' });
              resolve({ dataUrl, blob: fallbackBlob });
            }
          },
          'image/jpeg',
          quality
        );
      };
      img.src = reader.result as string;
    };
    reader.readAsDataURL(file);
  });
}

export interface UploadImageResult {
  imageUrl?: string;
  imageData?: string;
}

/**
 * Bulletproof Product Image Upload:
 * 1. Validates image type and 10 MB maximum size.
 * 2. Compresses image in browser BEFORE any upload (max 800px, quality 0.6, <300 KB).
 * 3. Tries Firebase Storage with 12-second timeout.
 * 4. Fallback if Firebase Storage fails or times out: stores compressed base64 in imageData
 *    and sets imageUrl to "". Document size stays far below 600 KB.
 */
export async function uploadProductImageWithFallback(
  file: File,
  productId: string,
  onProgress?: (progressPercent: number) => void
): Promise<UploadImageResult> {
  // 1. Validation checks
  if (file.size > 10 * 1024 * 1024) {
    const err: any = new Error('L’image dépasse la taille maximale autorisée de 10 Mo');
    err.code = 'invalid-argument';
    throw err;
  }
  if (!file.type.startsWith('image/')) {
    const err: any = new Error('Le fichier sélectionné doit être une image (JPEG, PNG, WebP)');
    err.code = 'invalid-argument';
    throw err;
  }

  // 2. ALWAYS resize and compress in browser BEFORE upload (< 300 KB)
  const { dataUrl, blob } = await compressImageFile(file);

  // 3. Try Firebase Storage with 12s timeout
  const tryUploadToStorage = (): Promise<string> => {
    return new Promise((resolve, reject) => {
      if (!storageInstance) {
        const err: any = new Error('Firebase Storage instance is not configured.');
        err.code = 'unavailable';
        return reject(err);
      }

      const cleanId = (productId || 'product').replace(/[^a-zA-Z0-9_-]/g, '');
      const storageRef = ref(storageInstance, `products/${cleanId}-${Date.now()}.jpg`);

      const uploadTask = uploadBytesResumable(storageRef, blob, { contentType: 'image/jpeg' });

      let isSettled = false;

      // 12-second timeout
      const timeoutTimer = setTimeout(() => {
        if (!isSettled) {
          isSettled = true;
          try {
            uploadTask.cancel();
          } catch (_) {}
          const err: any = new Error('Délai d’attente dépassé (12s) lors de l’envoi vers Firebase Storage.');
          err.code = 'timeout';
          reject(err);
        }
      }, 12000);

      uploadTask.on(
        'state_changed',
        (snapshot) => {
          if (snapshot.totalBytes > 0 && onProgress) {
            const percent = Math.round((snapshot.bytesTransferred / snapshot.totalBytes) * 100);
            onProgress(percent);
          }
        },
        (error) => {
          if (!isSettled) {
            isSettled = true;
            clearTimeout(timeoutTimer);
            reject(error);
          }
        },
        async () => {
          if (!isSettled) {
            isSettled = true;
            clearTimeout(timeoutTimer);
            try {
              const downloadUrl = await getDownloadURL(uploadTask.snapshot.ref);
              resolve(downloadUrl);
            } catch (urlErr) {
              reject(urlErr);
            }
          }
        }
      );
    });
  };

  try {
    const hostedUrl = await withTimeout(
      tryUploadToStorage(),
      12000,
      'Délai d’attente Storage dépassé (12s)'
    );
    return { imageUrl: hostedUrl, imageData: '' };
  } catch (storageErr) {
    console.warn(
      'Firebase Storage direct upload notice (falling back to compressed Firestore imageData):',
      storageErr
    );
    // Fallback: Store compressed base64 in imageData and set imageUrl to ""
    return { imageData: dataUrl, imageUrl: '' };
  }
}

// Backward-compatible alias
export async function uploadProductImage(file: File, productId: string): Promise<string> {
  const res = await uploadProductImageWithFallback(file, productId);
  return res.imageUrl || res.imageData || '';
}

/**
 * Delete a product image from Firebase Storage if it is a hosted storage URL
 */
export async function deleteProductImage(imageUrl?: string): Promise<void> {
  if (!imageUrl || !storageInstance) return;

  if (imageUrl.includes('firebasestorage.googleapis.com') || imageUrl.includes('firebasestorage.app')) {
    try {
      const storageRef = ref(storageInstance, imageUrl);
      await deleteObject(storageRef);
    } catch (err) {
      console.warn('Firebase Storage image deletion notice (non-fatal):', err);
    }
  }
}

/**
 * Health check on startup:
 * Runs a read and a tiny write to _health
 */
export interface HealthCheckResult {
  ok: boolean;
  code?: string;
  message?: string;
  stage?: 'read' | 'write' | 'init';
}

export async function runStartupHealthCheck(): Promise<HealthCheckResult> {
  if (!db) {
    return { ok: false, stage: 'init', code: 'unavailable', message: 'Firestore instance non initialisée' };
  }
  const healthDocRef = doc(db, '_health', 'status');

  // 1. Tiny write
  try {
    await withTimeout(
      setDoc(healthDocRef, {
        lastPing: Date.now(),
        client: 'admin-health-check'
      }),
      8000,
      'Délai d’attente dépassé lors de l’écriture vers _health'
    );
  } catch (err: any) {
    return {
      ok: false,
      stage: 'write',
      code: err?.code || (err?.message?.includes('timeout') ? 'timeout' : 'error'),
      message: err?.message || String(err)
    };
  }

  // 2. Read back
  try {
    const snap = await withTimeout(
      getDoc(healthDocRef),
      8000,
      'Délai d’attente dépassé lors de la lecture de _health'
    );
    if (!snap.exists()) {
      return { ok: false, stage: 'read', code: 'not-found', message: 'Document _health non trouvé' };
    }
  } catch (err: any) {
    return {
      ok: false,
      stage: 'read',
      code: err?.code || (err?.message?.includes('timeout') ? 'timeout' : 'error'),
      message: err?.message || String(err)
    };
  }

  return { ok: true };
}
